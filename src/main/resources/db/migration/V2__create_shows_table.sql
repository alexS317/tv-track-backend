CREATE TYPE show_status AS ENUM ('PLANNED', 'WATCHING', 'FINISHED');

CREATE TABLE IF NOT EXISTS shows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    tvmaze_id BIGINT NOT NULL,
    status show_status NOT NULL DEFAULT 'PLANNED',
    personal_rating INTEGER CHECK (personal_rating BETWEEN 1 AND 10),
    started_watching DATE,
    finished_watching DATE,
    current_episode_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, tvmaze_id)
);